import { useEffect, useState } from 'react'
import type { Feed } from '../../shared/feed.ts'

export type FeedState = { status: 'loading' } | { status: 'error' } | { status: 'ready'; feed: Feed }

let primed: Feed | null = null

/** Sets the feed for the prerender (scripts/prerender.ts), where there is no DOM to read it from. */
export function primeFeed(feed: Feed | null) {
  primed = feed
}

/** The production build embeds the feed in the page, so the first render already has the content. */
function embeddedFeed(): Feed | null {
  if (primed || typeof document === 'undefined') return primed
  const el = document.getElementById('feed-data')
  if (!el?.textContent) return null
  try {
    return JSON.parse(el.textContent) as Feed
  } catch {
    return null
  }
}

/** Loads the feed generated by scripts/fetch-data.ts: embedded in the page, or fetched (dev server). */
export function useFeed(): FeedState {
  const [state, setState] = useState<FeedState>(() => {
    const feed = embeddedFeed()
    return feed ? { status: 'ready', feed } : { status: 'loading' }
  })

  // fetch once, only when nothing was embedded
  useEffect(() => {
    if (state.status !== 'loading') return
    const controller = new AbortController()
    // every deploy gets a new build id, which busts caches
    fetch(`/data/feed.json?v=${__BUILD_TIME__}`, { signal: controller.signal })
      .then((res) => {
        if (!res.ok) throw new Error(res.statusText)
        return res.json() as Promise<Feed>
      })
      .then((feed) => setState({ status: 'ready', feed }))
      .catch((err: Error) => {
        if (err.name !== 'AbortError') setState({ status: 'error' })
      })
    return () => controller.abort()
  }, [])

  return state
}
